# plugins/ai.py
import urllib.parse
import aiohttp
from pyrogram import Client, filters
from pyrogram.types import Message

# 🔥 অটোমেটিক ডাইনামিক হেল্প মেনুর জন্য পরিচিতি 🔥
HELP = {
    "ai <প্রশ্ন>": "টেক্সট এআই: যেকোনো প্রশ্ন, কোডিং, অনুবাদ বা কনটেন্ট লিখতে",
    "img <বিবরণ>": "ইমেজ এআই: যেকোনো ছবি, আর্ট বা লোগো তৈরি করতে"
}

# সিস্টেম প্রম্পট (এআই-এর চরিত্র নির্ধারণ)
SYSTEM_PROMPT = (
    "You are OmniCore AI, an ultra-intelligent, creative, and polite AI assistant. "
    "Provide clear, concise, and beautifully formatted answers using markdown. "
    "If asked in Bengali, reply naturally and accurately in Bengali."
)

# ----------------- [ ১. টেক্সট এআই হ্যান্ডলার ] -----------------
@Client.on_message(filters.command("ai"))
async def text_ai_handler(client: Client, message: Message):
    prompt = None

    # ১. যদি সরাসরি লিখে প্রশ্ন করে: /ai পাইথনে কীভাবে কোড লিখব?
    if len(message.command) > 1:
        prompt = message.text.split(None, 1)[1].strip()
    # ২. অথবা কোনো মেসেজে Reply দিয়ে /ai লিখলে
    elif message.reply_to_message and message.reply_to_message.text:
        prompt = message.reply_to_message.text.strip()

    if not prompt:
        await message.reply_text(
            "💡 **ব্যবহারের নিয়ম:**\n\n"
            "`/ai আপনার প্রশ্ন বা নির্দেশনা`\n"
            "অথবা কোনো মেসেজে **Reply** করে লিখুন: `/ai এটিকে বাংলায় অনুবাদ করো`"
        )
        return

    # টাইপিং অ্যাকশন ও স্ট্যাটাস মেসেজ
    status_msg = await message.reply_text("🧠 **চিন্তাভাবনা করছি, কিছুক্ষণ অপেক্ষা করুন...**")

    try:
        # এআই ইঞ্জিনের জন্য প্রম্পট এনকোড করা
        encoded_prompt = urllib.parse.quote(prompt)
        encoded_system = urllib.parse.quote(SYSTEM_PROMPT)
        api_url = f"https://text.pollinations.ai/{encoded_prompt}?system={encoded_system}"

        async with aiohttp.ClientSession() as session:
            async with session.get(api_url, timeout=60) as resp:
                if resp.status == 200:
                    answer = await resp.text()
                    answer = answer.strip()

                    # টেলিগ্রামের মেসেজ লিমিট (৪০৯৬ অক্ষর) হ্যান্ডেল করা
                    if len(answer) > 4000:
                        answer = answer[:4000] + "\n\n*(উত্তর অনেক বড় হওয়ায় বাকি অংশ কেটে দেওয়া হলো)*"

                    await status_msg.edit_text(answer)
                else:
                    await status_msg.edit_text("❌ দুঃখিত, এআই সার্ভার থেকে উত্তর দিতে ব্যর্থ হয়েছে। পরে চেষ্টা করুন।")

    except Exception as e:
        await status_msg.edit_text("❌ নেটওয়ার্ক টাইমআউট বা টেকনিক্যাল সমস্যা হয়েছে!")
        print(f"[AI Text Error]: {e}")


# ----------------- [ ২. ইমেজ ও লোগো ক্রিয়েটর ] -----------------
@Client.on_message(filters.command(["img", "draw", "logo"]))
async def image_ai_handler(client: Client, message: Message):
    if len(message.command) < 2:
        await message.reply_text(
            "🎨 **ইমেজ ও লোগো তৈরির নিয়ম:**\n\n"
            "যেমন:\n"
            "`/img a minimalist modern tech logo with letter O and blue glowing neon`\n"
            "`/img a cute baby cat flying in space, 4k digital art`"
        )
        return

    prompt = message.text.split(None, 1)[1].strip()
    status_msg = await message.reply_text("🎨 **আপনার কল্পনার ছবি/লোগো তৈরি হচ্ছে, অপেক্ষা করুন...**")

    try:
        # প্রম্পট থেকে সরাসরি এইচডি ইমেজ জেনারেট করা
        encoded_prompt = urllib.parse.quote(prompt)
        image_url = f"https://image.pollinations.ai/prompt/{encoded_prompt}?width=1024&height=1024&nologo=true&model=flux"

        # টেলিগ্রামে ফটো আকারে পাঠিয়ে দেওয়া
        await message.reply_photo(
            photo=image_url,
            caption=f"✨ **প্রম্পট:** `{prompt}`\n\n🤖 Generated by **OmniCore AI**"
        )
        await status_msg.delete()

    except Exception as e:
        await status_msg.edit_text("❌ ইমেজ তৈরি করা সম্ভব হয়নি। প্রম্পটটি আরেকটু সহজ করে চেষ্টা করুন।")
        print(f"[AI Image Error]: {e}")
